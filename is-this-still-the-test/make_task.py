def render(df: pd.DataFrame, dataset_name: str, repeats: int, n_jobs: int, max_passes: int,
           choose: bool) -> str:
    blob, sha, n = embed_dataset(df)
    choose_cell = (f"\n# %%\n# %choose {LEADERBOARD_TASK}\n" if choose else
                   f"\n# %%\n# Leaderboard task: {LEADERBOARD_TASK} (the only stored task). The per-row\n"
                   f"# run files were pruned above, which is the same file set the notebook\n"
                   f"# magic 'choose {LEADERBOARD_TASK}' would leave. Re-run make_task.py\n"
                   f"# without --no-choose to emit the live magic cell.\n")
    subs = {
        "__SCORING__": scoring_source(),
        "__LEADERBOARD_TASK__": LEADERBOARD_TASK,
        "__ROW_TASK__": ROW_TASK,
        "__N_REPEATS__": str(int(repeats)),
        "__N_JOBS__": str(int(n_jobs)),
        "__MAX_PASSES__": str(int(max_passes)),
        "__DATASET_NAME__": dataset_name,
        "__DATASET_SHA256__": sha,
        "__DATASET_ROWS__": str(n),
        "__DATASET_SCENARIOS__": str(int(df.scenario_id.nunique())),
        "__DATASET_BLOB__": blob,
        "__CHOOSE__": choose_cell,
    }
    for key in subs:
        if key not in TEMPLATE:
            raise SystemExit(f"template lacks placeholder {key}")
    out = TEMPLATE
    for key, val in subs.items():
        out = out.replace(key, val)
    leftover = [k for k in subs if k in out.replace(subs["__SCORING__"], "")]
    if leftover:
        raise SystemExit(f"template placeholders left unreplaced: {leftover}")
    ast.parse(out, feature_version=MIN_PY)  # magics are comments in the .py, so it must parse
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--smoke", action="store_true", help="data/scenarios_smoke.parquet -> task_smoke.py, 1 repeat")
    ap.add_argument("--dataset", help="parquet to embed (default data/scenarios.parquet)")
    ap.add_argument("--out", help="output file (default task.py / task_smoke.py)")
    ap.add_argument("--repeats", type=int, default=None,
                    help=f"repeats per row (default {DEFAULT_REPEATS}; {SMOKE_REPEATS} with --smoke)")
    ap.add_argument("--scenarios", type=int, default=None, help="keep only the first N stories")
    ap.add_argument("--n-jobs", type=int, default=4)
    ap.add_argument("--max-passes", type=int, default=3)
    ap.add_argument("--no-choose", dest="choose", action="store_false",
                    help="omit the final live `%%choose` magic cell (emitted by default)")
    args = ap.parse_args(argv)

    repeats = args.repeats if args.repeats is not None else (SMOKE_REPEATS if args.smoke else DEFAULT_REPEATS)
    if repeats < 1 or args.n_jobs < 1 or args.max_passes < 1 or (args.scenarios is not None and args.scenarios < 1):
        raise SystemExit("--repeats, --scenarios, --n-jobs and --max-passes must be >= 1")
    ds = Path(args.dataset) if args.dataset else ROOT / "data" / (
        "scenarios_smoke.parquet" if args.smoke else "scenarios.parquet")
    out = Path(args.out) if args.out else ROOT / ("task_smoke.py" if args.smoke else "task.py")
    df = first_scenarios(pd.read_parquet(ds), args.scenarios)
    rel = ds.relative_to(ROOT).as_posix() if ds.is_relative_to(ROOT) else ds.name
    if args.scenarios:
        rel += f" (first {args.scenarios} scenarios)"
    text = render(df, rel, repeats, args.n_jobs, args.max_passes, args.choose)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(df)} rows ({df.scenario_id.nunique()} scenarios) x {repeats} repeat(s) = "
          f"{len(df) * repeats} calls/model, {len(text) / 1024:.0f} KiB. "
          f"Push: kaggle b t push {LEADERBOARD_TASK} -f {out.name} --wait")
    return 0


if __name__ == "__main__":
    sys.exit(main())
