import ast
import base64
import hashlib
import json
import sys
import textwrap
import zlib
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
LEADERBOARD_TASK = "reality-threshold"   # push slug; must match @kbench.task(name=...)
ROW_TASK = "itst-decision"               # must NOT start with LEADERBOARD_TASK (%choose regex)
EMBED_COLUMNS = ["row_id", "scenario_id", "condition", "arm", "expected_action",
                 "transcript", "scope_targets", "decision_host"]
MIN_PY = (3, 10)                         # syntax floor for the generated file
DEFAULT_REPEATS = 2
SMOKE_REPEATS = 1


def scoring_source() -> str:
    """scoring.py minus its module docstring (everything else verbatim)."""
    src = (ROOT / "scoring.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    if any(isinstance(n, ast.ImportFrom) and n.module == "__future__" for n in tree.body):
        raise SystemExit("scoring.py must not use `from __future__` (cannot be inlined)")
    first = tree.body[0]
    if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) \
            and isinstance(first.value.value, str):
        lines = src.splitlines(keepends=True)
        src = "".join(lines[first.end_lineno:])
    return src.strip("\n") + "\n"


def dataset_sha(df: pd.DataFrame) -> str:
    return hashlib.sha256(_canonical(df)).hexdigest()


def _canonical(df: pd.DataFrame) -> bytes:
    records = df[EMBED_COLUMNS].astype(str).to_dict(orient="records")
    return json.dumps(records, ensure_ascii=True, sort_keys=True, separators=(",", ":")).encode("ascii")


def embed_dataset(df: pd.DataFrame) -> tuple[str, str, int]:
    missing = [c for c in EMBED_COLUMNS if c not in df.columns]
    if missing:
        raise SystemExit(f"dataset lacks columns {missing}; run build_dataset.py (contract v2) first")
    raw = _canonical(df)
    sha = hashlib.sha256(raw).hexdigest()
    b64 = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
    chunks = textwrap.wrap(b64, 96)
    blob = "(\n" + "".join(f'    "{c}"\n' for c in chunks) + ")"
    return blob, sha, len(df)


def first_scenarios(df: pd.DataFrame, n: int | None) -> pd.DataFrame:
    if not n:
        return df
    keep = list(dict.fromkeys(df.scenario_id))[:n]
    if len(keep) < n:
        raise SystemExit(f"--scenarios {n} but the dataset has only {len(keep)} stories")
    return df[df.scenario_id.isin(keep)].reset_index(drop=True)


