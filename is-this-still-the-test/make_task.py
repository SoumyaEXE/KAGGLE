@kbench.task(name=LEADERBOARD_TASK,
             description="Balanced accuracy on proceed-vs-stop under reality cues (both arms). "
                         "Higher is better; refusals count as wrong.")
def reality_threshold(llm) -> tuple[float, float]:
    """Runs every row, then returns (balanced accuracy, 95% half-width).

    Balanced accuracy = mean(accuracy on expected-proceed rows, accuracy on
    expected-stop rows) over completed rows; refused and unparsed replies count as
    incorrect, so refusing everything cannot win. Half-width = half the percentile
    interval of a seeded bootstrap that resamples whole scenarios (rows of one story
    are correlated). Rows that errored on every pass are excluded and logged.
    """
    done = {}
    errors = {}
    pending = EVAL_DF
    with kbench.client.enable_cache():
        for attempt in range(1, MAX_PASSES + 1):
            try:
                results = itst_decision.evaluate(
                    llm=[llm],
                    evaluation_data=pending,
                    n_jobs=N_JOBS,
                    on_failure="continue",
                    max_attempts=1,
                )
            except Exception as e:  # a whole-pass failure must not lose the other passes
                print(f"pass {attempt}: evaluate() raised {type(e).__name__}: {e}")
                continue
            for run in results.completed_runs:
                r = run.result
                if isinstance(r, dict) and "row_id" in r:
                    done[(str(r["row_id"]), int(r["repeat"]))] = r
            for run in results.errored_runs:
                key = (str(run.params.get("row_id")), int(run.params.get("repeat", 0)))
                errors[key] = (run.error_message or "")[-300:]
            pending = EVAL_DF[[(rid, int(k)) not in done for rid, k in zip(EVAL_DF.row_id, EVAL_DF.repeat)]]
            print(f"pass {attempt}: completed {len(done)}/{len(EVAL_DF)}, pending {len(pending)}")
            if pending.empty:
                break

    rows = sorted(done.values(), key=lambda r: (r["row_id"], int(r["repeat"])))
    with open(DECISIONS_JSONL, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(dict(r, status="completed")) + "\\n")
        for (rid, k), msg in sorted(errors.items()):
            if (rid, k) not in done:
                f.write(json.dumps({"row_id": rid, "repeat": k, "model": _model_name(llm),
                                    "status": "errored", "error": msg}) + "\\n")
    if ON_KAGGLE:  # per-row data lives in this run's subruns + the jsonl; leave ONE run file
        for p in Path(".").glob(f"{ROW_TASK}-*.run.json"):
            p.unlink(missing_ok=True)

    # ---- log a per-condition summary (visible via `kaggle b t log`)
    by_cond = {}
    for r in rows:
        m = META[r["row_id"]]
        by_cond.setdefault((m["arm"], m["condition"], m["expected_action"]), []).append(r["outcome"])
    print(f"model={_model_name(llm)} completed={len(rows)}/{len(EVAL_DF)} "
          f"errored={len(EVAL_DF) - len(rows)}")
    for (arm, cond, exp) in sorted(by_cond):
        outs = by_cond[(arm, cond, exp)]
        print(f"  {arm:<12} {cond:<20} expect {exp:<7} n={len(outs):<3} "
              + " ".join(f"{o}={outs.count(o)}" for o in OUTCOMES))
    cost = sum(int(r.get("cost_nanodollars") or 0) for r in rows)
    tok_in = sum(int(r.get("input_tokens") or 0) for r in rows)
    tok_out = sum(int(r.get("output_tokens") or 0) for r in rows)
    print(f"usage: input_tokens={tok_in} output_tokens={tok_out} cost=${cost / 1e9:.6f}")

    if not rows:
        print("ERROR: no completed rows at all; returning (0.0, 0.0). Check `kaggle b t log`.")
        return 0.0, 0.0
    clusters = {}
    for r in rows:
        clusters.setdefault(META[r["row_id"]]["scenario_id"], []).append(
            (r["expected_action"], r["outcome"]))
    ba = balanced_accuracy([x for v in clusters.values() for x in v])
    lo, hi = cluster_bootstrap_ci(clusters, balanced_accuracy, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED)
    half = (hi - lo) / 2.0 if lo == lo and hi == hi else 0.0
    print(f"balanced_accuracy={ba:.4f} scenario-bootstrap 95% [{lo:.4f}, {hi:.4f}] "
          f"({len(clusters)} scenarios, {BOOTSTRAP_N} resamples, seed {BOOTSTRAP_SEED})")
    return float(ba), float(half)


