def load_dataset():
    raw = zlib.decompress(base64.b64decode("".join(_DATASET_B64)))
    sha = hashlib.sha256(raw).hexdigest()
    if sha != DATASET_SHA256:
        raise RuntimeError(f"embedded dataset corrupted: sha256 {sha} != {DATASET_SHA256}")
    df = pd.DataFrame(json.loads(raw.decode("ascii")))
    if len(df) != DATASET_ROWS or df["row_id"].duplicated().any():
        raise RuntimeError(f"embedded dataset has {len(df)} rows / duplicate row_ids")
    if df["scenario_id"].nunique() != DATASET_SCENARIOS:
        raise RuntimeError("embedded dataset scenario count mismatch")
    return df


